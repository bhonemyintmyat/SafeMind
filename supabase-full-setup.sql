-- 1. Administrators ---------------------------------------------------------
create table if not exists public.admin_accounts (
    email text primary key check (email = lower(email))
);
alter table public.admin_accounts enable row level security;

create or replace function public.is_safemind_admin()
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $$
    select exists (
        select 1
        from public.admin_accounts
        where email = lower(coalesce(auth.jwt() ->> 'email', ''))
    );
$$;
revoke all on function public.is_safemind_admin() from public;
grant execute on function public.is_safemind_admin() to authenticated;

