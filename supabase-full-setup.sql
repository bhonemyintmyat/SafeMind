create or replace function public.award_scan_credit(scan_kind text, scan_risk text)
returns table (credits integer, total_scans integer, current_streak integer)
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    today date := current_date;
begin
    if auth.uid() is null
       or scan_kind not in ('message', 'link', 'phone', 'email')
       or scan_risk not in ('low', 'medium', 'high') then
        raise exception 'Invalid scan';
    end if;
    if exists (
        select 1 from public.user_scan_history
        where user_id = auth.uid() and created_at > now() - interval '5 seconds'
    ) then
        return query
        select p.credits, p.total_scans, p.current_streak
        from public.user_scan_progress p where p.user_id = auth.uid();
        return;
    end if;
    insert into public.user_scan_history (user_id, scan_type, risk)
    values (auth.uid(), scan_kind, scan_risk);
    insert into public.user_scan_progress
        (user_id, credits, total_scans, current_streak, last_scan_date)
    values (auth.uid(), 10, 1, 1, today)
    on conflict (user_id) do update set
        credits = user_scan_progress.credits + 10,
        total_scans = user_scan_progress.total_scans + 1,
        current_streak = case
            when user_scan_progress.last_scan_date = today then user_scan_progress.current_streak
            when user_scan_progress.last_scan_date = today - 1 then user_scan_progress.current_streak + 1
            else 1
        end,
        last_scan_date = today,
        updated_at = now();
    return query
    select p.credits, p.total_scans, p.current_streak
    from public.user_scan_progress p where p.user_id = auth.uid();
end;
$$;
revoke all on function public.award_scan_credit(text, text) from public;
grant execute on function public.award_scan_credit(text, text) to authenticated;

